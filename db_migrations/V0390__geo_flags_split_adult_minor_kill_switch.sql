-- Разделение единого выключателя геолокации на целевые флаги (adult/minor/history/geofences)
-- + глобальный emergency kill switch, который стоит ВЫШЕ всех остальных флагов.
--
-- Почему разделяем: единый флаг однажды включённый открыл бы сразу все
-- сценарии геолокации, включая детский, для которого достоверность
-- заявления о представительстве (self_declared, не verified) пока
-- недостаточна для production. Раздельные флаги позволяют включить
-- self-tracking взрослых, оставив детский сценарий и историю выключенными.

INSERT INTO t_p5815085_family_assistant_pro.feature_flags (flag_key, is_enabled, description)
VALUES
  ('geolocation_emergency_kill_switch', false,
   'Аварийный общий выключатель геолокации. Если TRUE — блокирует ВСЕ операции с геоданными независимо от остальных geo-флагов. Единственный флаг, который проверяется раньше и важнее любого другого.'),
  ('geolocation_adult_self_collection_enabled', false,
   'Совершеннолетний участник с собственным аккаунтом включает передачу СОБСТВЕННОГО местоположения и сам выбирает получателей. Единственный сценарий, готовящийся к первому production-запуску.'),
  ('geolocation_minor_collection_enabled', false,
   'Геолокация несовершеннолетних участников (согласие через заявление о представительстве). ВЫКЛЮЧЕНО: самодекларация (self_declared) пока недостаточна как единственное основание для доступа к детской геолокации без решения юриста.'),
  ('geolocation_geofences_enabled', false,
   'Геозоны и уведомления о входе/выходе. Отдельный флаг: адреса геозон (дом, школа) — самостоятельная категория чувствительных данных.')
ON CONFLICT (flag_key) DO NOTHING;

-- Переименовываем описание старых флагов, чтобы не создавалось впечатление,
-- что они по-прежнему единственный источник истины — теперь это узкие
-- технические тумблеры (запись новой точки / чтение истории), а решение
-- "для кого именно" принимают adult/minor флаги поверх них.
UPDATE t_p5815085_family_assistant_pro.feature_flags
SET description = 'Технический тумблер: разрешена ли запись новых координат ВООБЩЕ (для любого сценария). Реальный допуск взрослый/ребёнок决ается через geolocation_adult_self_collection_enabled и geolocation_minor_collection_enabled — они проверяются дополнительно.'
WHERE flag_key = 'geolocation_collection_enabled';

UPDATE t_p5815085_family_assistant_pro.feature_flags
SET description = 'Технический тумблер: разрешена ли выдача истории перемещений ВООБЩЕ. Пока выключено: retention-cron ещё не прошёл проверку реального физического удаления.'
WHERE flag_key = 'geolocation_history_enabled';
